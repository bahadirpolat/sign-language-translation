import numpy as np

class BeamSearch:
    def __init__(self,
                 max_length=200,
                 max_new_tokens=128,
                 length_penalty=1.0,
                 top_k=10,
                 top_p=0.95,
                 temperature=1.0,
                 no_repeat_ngram_size=3,
                 repetition_penalty=1.2,
                 num_beams=5,
                 do_sample=True,
                 eos_token_id=None):
        self.max_length = max_length
        self.max_new_tokens = max_new_tokens
        self.length_penalty = length_penalty
        self.top_k = top_k
        self.top_p = top_p
        self.temperature = temperature
        self.no_repeat_ngram_size = no_repeat_ngram_size
        self.repetition_penalty = repetition_penalty
        self.num_beams = num_beams
        self.do_sample = do_sample
        self.eos_token_id = eos_token_id  # End-of-sequence token ID

    def generate(self, initial_logits, next_logits_fn):
        """
        Perform beam search starting from initial logits and generating sequences by
        requesting the next logits one at a time.

        Args:
            initial_logits (np.ndarray): The initial logits array at time step 0.
            next_logits_fn (callable): A function that takes a sequence (list of token IDs)
                                       and returns the logits for the next time step.

        Returns:
            argmax_sequence: The sequence generated by taking argmax of the initial logits.
            generated_sequences: List of generated sequences with their scores.
        """
        # Initialize sequences with empty sequence and zero score
        sequences = [([], 0.0)]  # Each element is a tuple (sequence, cumulative_score)
        completed_sequences = []

        # Use initial_logits to start the beam search
        logits = initial_logits

        # Determine argmax sequence from all logits
        argmax_token = np.argmax(logits)
        argmax_sequence = np.argmax(logits, axis=-1)

        for t in range(self.max_new_tokens):
            all_candidates = []

            for seq, score in sequences:
                # If sequence ends with EOS token, add to completed_sequences
                if self.eos_token_id is not None and seq and seq[-1] == self.eos_token_id:
                    completed_sequences.append((seq, score))
                    continue

                # Adjust logits for temperature and repetition penalty
                logits_adjusted = np.copy(logits)

                # Apply repetition penalty
                logits_adjusted = self.apply_repetition_penalty(logits_adjusted, seq)

                # Apply temperature
                logits_adjusted = logits_adjusted / self.temperature

                # Convert logits to log probabilities
                log_probs = self.log_softmax(logits_adjusted)

                # Apply top_k and top_p filtering if sampling
                if self.do_sample:
                    next_token_ids = self.sample_next_tokens(log_probs)
                else:
                    # Select top num_beams tokens
                    next_token_ids = np.argsort(log_probs)[-self.num_beams:]

                # Expand each sequence with possible next tokens
                for token_id in next_token_ids:
                    candidate_seq = seq + [int(token_id)]

                    # Apply no_repeat_ngram constraint
                    if self.no_repeat_ngram_size > 0 and self.has_repeat_ngram(candidate_seq):
                        continue

                    candidate_score = score + log_probs[token_id]
                    all_candidates.append((candidate_seq, candidate_score))

            # If no candidates, break
            if not all_candidates:
                break

            # Sort all candidates by score and select top num_beams
            ordered = sorted(all_candidates, key=lambda tup: tup[1], reverse=True)
            sequences = ordered[:self.num_beams]

            # Update logits for next time step using next_logits_fn
            # Since we have multiple sequences, we need to get logits for each
            new_sequences = []
            for seq, score in sequences:
                if self.eos_token_id is not None and seq[-1] == self.eos_token_id:
                    completed_sequences.append((seq, score))
                    continue

                # Get next logits using next_logits_fn
                logits = next_logits_fn(seq)
                new_sequences.append((seq, score))

            sequences = new_sequences

            # Check if max_new_tokens is reached
            if t >= self.max_new_tokens - 1:
                completed_sequences.extend(sequences)
                break

        # If no completed sequences, add current sequences
        if not completed_sequences:
            completed_sequences.extend(sequences)

        # Apply length penalty
        sequences_with_penalty = [
            (seq, score / (len(seq) ** self.length_penalty)) for seq, score in completed_sequences
        ]

        # Sort sequences by score
        sequences_with_penalty.sort(key=lambda tup: tup[1], reverse=True)

        # Return argmax sequence and generated sequences
        generated_sequences = sequences_with_penalty

        return argmax_sequence, generated_sequences

    def apply_repetition_penalty(self, logits, sequence):
        """
        Apply repetition penalty to logits.
        """
        for token_id in set(sequence):
            logits[token_id] /= self.repetition_penalty
        return logits

    def log_softmax(self, logits):
        """
        Compute log softmax of logits for numerical stability.
        """
        max_logits = np.max(logits)
        logits = logits - max_logits
        exp_logits = np.exp(logits)
        sum_exp = np.sum(exp_logits)
        log_probs = logits - np.log(sum_exp)
        return log_probs

    def sample_next_tokens(self, log_probs):
        """
        Sample next tokens using top_k and top_p filtering.
        """
        sorted_indices = np.argsort(log_probs)[::-1]
        sorted_log_probs = log_probs[sorted_indices]

        # Apply top_k filtering
        if self.top_k > 0:
            sorted_indices = sorted_indices[:self.top_k]
            sorted_log_probs = sorted_log_probs[:self.top_k]

        # Apply top_p filtering
        cumulative_probs = np.cumsum(np.exp(sorted_log_probs))
        cutoff_index = np.where(cumulative_probs > self.top_p)[0]
        if len(cutoff_index) > 0:
            cutoff = cutoff_index[0] + 1  # Include the token that exceeds top_p
            sorted_indices = sorted_indices[:cutoff]
            sorted_log_probs = sorted_log_probs[:cutoff]

        # Sample from the filtered logits
        probabilities = np.exp(sorted_log_probs)
        probabilities /= probabilities.sum()
        next_token_id = np.random.choice(sorted_indices, p=probabilities)
        return [next_token_id]

    def has_repeat_ngram(self, sequence):
        """
        Check if the sequence contains any repeated n-grams of size no_repeat_ngram_size.
        """
        n = self.no_repeat_ngram_size
        if len(sequence) < n:
            return False
        ngram = sequence[-n:]
        for i in range(len(sequence) - n):
            if sequence[i:i + n] == ngram:
                return True
        return False

